-- Google Forms as a lead source: lead_sources.provider = 'GOOGLE_FORMS'.
--
-- This migration adds the enum value and NOTHING else, on purpose. Postgres
-- refuses to use a value added by ALTER TYPE inside the same transaction that
-- added it, and Prisma wraps each migration file in one transaction — so any
-- statement that referenced 'GOOGLE_FORMS' here would fail at deploy time.
-- Everything that uses the value goes in a later migration, or in no migration
-- at all: the Google Forms source reuses the lead_sources columns that Tally,
-- Typeform and Google Sheets already have (external_form_id, integration_id,
-- schema_fingerprint, the ingest token, the signing secret, and the
-- sync_next_at / sync_locked_at lease), so no new column is needed.
--
-- Additive: no existing row, default or constraint changes.
ALTER TYPE "lead_source_provider" ADD VALUE IF NOT EXISTS 'GOOGLE_FORMS';
